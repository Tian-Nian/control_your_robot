"""Unified TTS and playback manager for trash-talk, chat, and transitions.

Supports two playback modes:
1. Legacy queued mode (speak_chat / speak_transition): synthesize full text, then play.
2. Streaming mode (speak_chat_streaming): edge-tts stream() → decode chunks → play via
   sounddevice as PCM, achieving first-audio latency of ~200-400ms.
"""

from __future__ import annotations

import asyncio
import io
import logging
import queue
import tempfile
import threading
import time
import uuid
from pathlib import Path
from typing import Optional

import edge_tts

try:
    from .audio_player import AudioPlayer
    from .trash_talk import TrashTalkManager
except ImportError:  # Allows `python main.py` inside voice_system/.
    from audio_player import AudioPlayer
    from trash_talk import TrashTalkManager

logger = logging.getLogger(__name__)


class TTSManager:
    """Coordinates local MP3 playback and realtime Edge-TTS generation.

    Policy:
    - Trash talk interrupts current audio so the taunt feels immediate.
    - Chat/transition speech is queued and played in order, so conversations do
      not cut themselves off mid-sentence.
    - speak_chat_streaming() bypasses the queue and plays directly via sounddevice
      for lowest latency.
    """

    def __init__(
        self,
        player: Optional[AudioPlayer] = None,
        trash_manager: Optional[TrashTalkManager] = None,
        voice: str = "zh-TW-HsiaoChenNeural",
        chat_rate: str = "-5%",
        tmp_dir: str | Path | None = None,
    ) -> None:
        self.player = player or AudioPlayer()
        self.trash_manager = trash_manager or TrashTalkManager()
        self.voice = voice
        self.chat_rate = chat_rate
        self.tmp_dir = Path(tmp_dir) if tmp_dir else Path(tempfile.gettempdir()) / "voice_system_tts"
        self.tmp_dir.mkdir(parents=True, exist_ok=True)

        self._queue: "queue.Queue[tuple[int, str, str]]" = queue.Queue()
        self._stop_event = threading.Event()
        self._generation = 0
        self._generation_lock = threading.RLock()
        self._busy = False  # True while worker is processing (synthesize + play + pause)
        self._streaming_busy = False  # True while streaming TTS is active

        self._worker = threading.Thread(target=self._worker_loop, name="voice-tts-worker", daemon=True)
        self._worker.start()

    @property
    def is_busy(self) -> bool:
        """True when TTS worker is actively synthesizing, playing, or in post-speech pause."""
        return self._busy or self._streaming_busy or not self._queue.empty()

    def speak_trash(self, event_type: str) -> bool:
        """Play a pre-generated trash-talk MP3 immediately."""
        path = self.trash_manager.get_random_audio(event_type)
        if path is None:
            return False
        return self.player.play(path, interrupt=True)

    def speak_chat(self, text: str) -> None:
        """Queue realtime chat TTS generation and playback (legacy non-streaming)."""
        self._enqueue("chat", text)

    def speak_chat_streaming(self, text: str) -> None:
        """Stream TTS synthesis and playback with minimal latency.

        Uses edge-tts stream() to get audio chunks and plays them via
        sounddevice as they arrive. Blocks until playback is complete.
        Call from a worker thread, not the main loop.
        """
        text = text.strip()
        if not text:
            return

        # Check if generation changed (i.e. stop() was called)
        with self._generation_lock:
            gen_before = self._generation

        self._streaming_busy = True
        try:
            asyncio.run(self._stream_and_play(text, gen_before))
        except Exception:
            logger.exception("Streaming TTS failed for: %s", text)
        finally:
            self._streaming_busy = False

    def speak_transition(self, text: str) -> None:
        """Queue transition speech generated by Edge-TTS."""
        self._enqueue("transition", text)

    def stop(self) -> None:
        """Stop current playback and drop queued chat/transition speech."""
        with self._generation_lock:
            self._generation += 1
        self.player.stop()
        self._drain_queue()

    def shutdown(self) -> None:
        """Stop background worker and release playback resources."""
        self._stop_event.set()
        self._drain_queue()
        self._worker.join(timeout=1.0)
        self.player.shutdown()

    # ------------------------------------------------------------------
    # Streaming TTS implementation
    # ------------------------------------------------------------------

    async def _stream_and_play(self, text: str, generation: int) -> None:
        """Edge-TTS stream → decode mp3 chunks → write to sounddevice output."""
        try:
            import sounddevice as sd
            import numpy as np
            from pydub import AudioSegment
        except ImportError:
            logger.warning(
                "sounddevice/pydub not available, falling back to queued TTS. "
                "Install: pip install sounddevice pydub"
            )
            # Fallback: use legacy queued mode
            self._enqueue("chat", text)
            return

        communicate = edge_tts.Communicate(text=text, voice=self.voice, rate=self.chat_rate)

        # Accumulate a small buffer before starting playback to avoid choppy start
        audio_buffer = io.BytesIO()
        stream: Optional[sd.OutputStream] = None
        sample_rate = None
        channels = None
        first_chunk_played = False

        # Minimum bytes before first flush (avoid tiny initial chunk artifacts)
        MIN_FIRST_FLUSH = 4096  # ~4KB of mp3 ≈ 100-200ms audio

        try:
            async for chunk in communicate.stream():
                # Check for cancellation
                with self._generation_lock:
                    if generation != self._generation:
                        logger.debug("Streaming TTS cancelled: %s", text)
                        return

                if chunk["type"] != "audio":
                    continue

                audio_buffer.write(chunk["data"])

                # Decide when to flush
                should_flush = False
                if not first_chunk_played:
                    if audio_buffer.tell() >= MIN_FIRST_FLUSH:
                        should_flush = True
                else:
                    # After first flush, flush every chunk for low latency
                    should_flush = True

                if should_flush and audio_buffer.tell() > 0:
                    audio_buffer.seek(0)
                    try:
                        seg = AudioSegment.from_file(audio_buffer, format="mp3")
                    except Exception:
                        # Incomplete mp3 frame, wait for more data
                        audio_buffer.seek(0, 2)  # seek to end
                        continue

                    # Initialize stream on first successful decode
                    if stream is None:
                        sample_rate = seg.frame_rate
                        channels = seg.channels
                        stream = sd.OutputStream(
                            samplerate=sample_rate,
                            channels=channels,
                            dtype="float32",
                        )
                        stream.start()

                    # Convert to float32 numpy array and play
                    samples = np.array(seg.get_array_of_samples(), dtype=np.float32)
                    # Normalize int16 → float32
                    samples = samples / 32768.0
                    if channels > 1:
                        samples = samples.reshape(-1, channels)
                    else:
                        samples = samples.reshape(-1, 1)

                    stream.write(samples)
                    first_chunk_played = True

                    # Reset buffer for next chunk
                    audio_buffer = io.BytesIO()

            # Flush any remaining audio
            if audio_buffer.tell() > 0:
                audio_buffer.seek(0)
                try:
                    seg = AudioSegment.from_file(audio_buffer, format="mp3")
                    if stream is None:
                        sample_rate = seg.frame_rate
                        channels = seg.channels
                        stream = sd.OutputStream(
                            samplerate=sample_rate,
                            channels=channels,
                            dtype="float32",
                        )
                        stream.start()

                    samples = np.array(seg.get_array_of_samples(), dtype=np.float32)
                    samples = samples / 32768.0
                    if channels and channels > 1:
                        samples = samples.reshape(-1, channels)
                    else:
                        samples = samples.reshape(-1, 1)
                    stream.write(samples)
                except Exception:
                    logger.debug("Could not decode final audio buffer remnant")

        finally:
            if stream is not None:
                # Small pause to let the last samples play out
                time.sleep(0.1)
                stream.stop()
                stream.close()

    # ------------------------------------------------------------------
    # Legacy queued TTS (kept for speak_transition and fallback)
    # ------------------------------------------------------------------

    def _enqueue(self, kind: str, text: str) -> None:
        text = text.strip()
        if not text:
            return
        with self._generation_lock:
            generation = self._generation
        self._queue.put((generation, kind, text))
        logger.debug("Queued %s speech: %s", kind, text)

    def _drain_queue(self) -> None:
        while True:
            try:
                self._queue.get_nowait()
                self._queue.task_done()
            except queue.Empty:
                return

    def _worker_loop(self) -> None:
        while not self._stop_event.is_set():
            try:
                generation, kind, text = self._queue.get(timeout=0.1)
            except queue.Empty:
                continue

            self._busy = True
            try:
                audio_path = self._synthesize_sync(text)
                with self._generation_lock:
                    is_stale = generation != self._generation
                if is_stale:
                    logger.debug("Drop stale %s speech after stop: %s", kind, text)
                    continue
                if audio_path:
                    while self.player.is_playing() and not self._stop_event.is_set():
                        time.sleep(0.03)
                        with self._generation_lock:
                            if generation != self._generation:
                                logger.debug("Drop stale %s speech while waiting: %s", kind, text)
                                audio_path = None
                                break
                    if audio_path:
                        self.player.play(audio_path, interrupt=False)
                    # Post-speech pause (still considered "busy")
                    time.sleep(0.9)
            except Exception:
                logger.exception("Failed to synthesize/play %s speech", kind)
            finally:
                self._busy = False
                self._queue.task_done()

    def _synthesize_sync(self, text: str) -> Optional[Path]:
        path = self.tmp_dir / f"edge_tts_{uuid.uuid4().hex}.mp3"
        try:
            asyncio.run(self._synthesize(text, path))
            return path
        except Exception:
            logger.exception("Edge-TTS synthesis failed: %s", text)
            return None

    async def _synthesize(self, text: str, output_path: Path) -> None:
        communicate = edge_tts.Communicate(text=text, voice=self.voice, rate=self.chat_rate)
        await communicate.save(str(output_path))
